import assert from 'node:assert/strict';
globalThis.location=new URL('https://farm.test/');
const m=await import('../farm/model.js');
const o=await import('../farm/orchard.js');
const T=1800000000000,H=3600000;
const old=m.newGame(T-48*H);
m.enableRain7(old);
o.enableOrchardMarket(old);
o.enableQuickFruit(old,T);
old.at=T;
old.coins=5000;
Object.assign(old.orchard,{basketCount:3,basketValue:395,basketRecent:['pear','plum','peach']});
const s=m.parse(JSON.stringify(old));
assert.deepEqual(o.basketLots(s.orchard),[{id:null,count:3,value:395}]);
assert(o.enableOrchardExpansion(s));
assert(!o.enableOrchardExpansion(s));
assert.deepEqual(s.orchard.trees,[...old.orchard.trees,null,null]);
assert.equal(s.coins,old.coins);
assert.equal(o.plantTree(s,3,'loquat',T),false);
assert.equal(o.plantTree(s,3,'persimmon',T).cost,750);
assert.equal(o.plantTree(s,4,'loquat',T).cost,650);
assert.equal(o.plantTree(s,3,'persimmon',T),false);
assert.deepEqual(m.parse(JSON.stringify(s)),s);
const first=T+15*60000;
assert(!o.treeView(s,3,first-1).stored);
assert(!o.treeView(s,4,first-1).stored);
const ripe=o.treeView(s,3,first);
assert.equal(ripe.stored,1);
assert.equal(o.treeView(s,4,first).stored,1);
assert(o.harvestFruit(s,3,ripe.fruits[0].token,first));
assert.equal(o.harvestFruit(s,3,ripe.fruits[0].token,first),false);
assert(o.harvestTree(s,4,first));
const incoming=m.parse(JSON.stringify(s));
assert.deepEqual(o.basketLots(incoming.orchard),[{id:null,count:3,value:395},{id:'persimmon',count:1,value:112},{id:'loquat',count:1,value:96}]);
const before=incoming.coins;
assert.equal(o.sellBasket(incoming,first,'persimmon').coins,112);
assert.deepEqual(o.basketLots(incoming.orchard),[{id:null,count:3,value:395},{id:'loquat',count:1,value:96}]);
assert.equal(o.sellBasket(incoming,first,null).coins,395);
assert.equal(o.sellBasket(incoming,first,null),false);
assert.equal(o.sellBasket(incoming,first).coins,96);
assert.equal(incoming.coins,before+603);
assert.equal(incoming.orchard.basketCount,0);
assert.equal(incoming.orchard.basketValue,0);
assert.deepEqual(m.parse(JSON.stringify(incoming)),incoming);
const all=m.parse(JSON.stringify(s));
assert.equal(o.sellBasket(all,T,undefined).coins,603);
assert.equal(o.sellBasket(all,T),false);
const altered=structuredClone(s);altered.orchard.basketLots[0].value++;
assert.throws(()=>m.parse(JSON.stringify(altered)),/总价/);
console.log('PASS five tree slots, unchanged legacy trees, first fruit, exact lot values, selective and all sales, aggregate compatibility');
